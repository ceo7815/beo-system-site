// Regenerates the committed responsive image variants.
// Requires `sharp` (not a site dependency): NODE_PATH=/path/to/node_modules node scripts/generate-responsive-images.mjs
import { createRequire } from "node:module";
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const require = createRequire(import.meta.url);
const sharp = require("sharp");

const root = path.resolve(import.meta.dirname, "..");
const blogDir = path.join(root, "public/blog");
const logo = path.join(root, "public/brand/logo-mark.png");
const blogWidths = [640, 960, 1280];
const logoWidths = [120, 240, 360, 500];

const blogFiles = (await readdir(blogDir)).filter((name) => name.endsWith(".webp") && !/-\d+\.webp$/.test(name)).sort();

const sizes = {};
for (const name of blogFiles) {
  const src = path.join(blogDir, name);
  const meta = await sharp(src).metadata();
  sizes[`/blog/${name}`] = { width: meta.width, height: meta.height };
  const stem = name.replace(/\.webp$/, "");
  for (const width of blogWidths) {
    if (!meta.width || width >= meta.width) continue;
    await sharp(src)
      .resize({ width, withoutEnlargement: true, kernel: "lanczos3" })
      .webp({ quality: 86, effort: 5, smartSubsample: false })
      .toFile(path.join(blogDir, `${stem}-${width}.webp`));
  }
}

for (const width of logoWidths) {
  await sharp(logo)
    .resize(width, width, { kernel: "lanczos3" })
    .webp({ lossless: true, effort: 6 })
    .toFile(path.join(root, `public/brand/logo-mark-${width}.webp`));
}

const lines = Object.entries(sizes).map(([key, value]) => `  ${JSON.stringify(key)}: { width: ${value.width}, height: ${value.height} },`);
await writeFile(
  path.join(root, "src/lib/content-images.ts"),
  `// Generated by scripts/generate-responsive-images.mjs — widths are the intrinsic sizes of public/blog/*.webp.\nexport const contentImageSize = {\n${lines.join("\n")}\n} as const;\n\nexport type ContentImageSrc = keyof typeof contentImageSize;\n\nexport const contentImageVariantWidths = [640, 960, 1280] as const;\n\nexport function contentImageSrcSet(src: string) {\n  const size = contentImageSize[src as ContentImageSrc];\n  if (!size) return undefined;\n  const stem = src.replace(/\\.webp$/, "");\n  const parts = contentImageVariantWidths\n    .filter((width) => width < size.width)\n    .map((width) => \`\${stem}-\${width}.webp \${width}w\`);\n  parts.push(\`\${src} \${size.width}w\`);\n  return parts.join(", ");\n}\n`,
);

console.log(`blog originals: ${blogFiles.length}`);
console.log(`logo widths: ${logoWidths.join(", ")}`);
